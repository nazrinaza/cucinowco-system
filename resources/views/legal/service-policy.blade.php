    <h2>1. Where we work</h2>
    <p>Our launch focus is Klang Valley, from our Sungai Buloh base. Larger or outstation projects are reviewed case by case.</p>

    <h2>2. Free site visit</h2>
    <p>A confirmed site assessment within our service coverage is free and carries no obligation. For locations outside Selangor, a site visit fee may apply depending on location, and we will tell you before the visit is confirmed. During the visit we review access, site condition, measurements and the right method.</p>

    <h2>3. Scope and quotation</h2>
    <p>We prepare a written quotation showing service scope, working area, timing and price. Work outside the agreed scope is quoted and agreed before it starts.</p>

    <h2>4. Booking lead time</h2>
    <p>We recommend booking two to five days ahead. Urgent requests are reviewed based on team availability and are not guaranteed.</p>

    <h2>5. Equipment, chemicals and manpower</h2>
    <p>We confirm the method, equipment, materials and manpower for each scope. Tell us about sensitive surfaces, pets or site restrictions so we can adjust. Disinfection and fragrance treatments are carried out as hygiene-focused cleaning; we do not make medical claims.</p>

    <h2>6. Access, safety and site conditions</h2>
    <ul>
        <li>Please arrange safe access, and water and electricity where needed.</li>
        <li>Work at height (such as window cleaning) and operational areas (such as warehouses) are planned around site safety rules.</li>
        <li>We may pause or reschedule work if conditions are unsafe, and will explain why.</li>
    </ul>

    <h2>7. Recurring office cleaning</h2>
    <p>We provide dedicated daily cleaners stationed at your office. The service is arranged on a monthly basis and billed monthly. Custom schedules can be agreed in writing.</p>

    <h2>8. Event cleaning</h2>
    <p>Pre-event preparation and post-event hall or venue cleaning are subject to access, timing and the programme agreed with you.</p>

    <h2>9. Rescheduling and cancellation</h2>
    <p>Please tell us as early as possible. Notice period: at least 48 hours before the scheduled service. If you cancel with less than 48 hours' notice, any deposit paid will be forfeited and is non-refundable. Where we must reschedule, we will offer the next available slot.</p>

    <h2>10. Payment</h2>
    <p>Payment methods and due dates appear on your quotation or invoice. SST is shown only where legally applicable.</p>

    <h2>11. Quality and feedback</h2>
    <p>We aim for a zero-defect standard and use client feedback to improve future service. Please inspect the work at handover and raise any concern within 48 hours through WhatsApp or email, with photos if possible. If the issue falls within the agreed scope, we will review it and arrange reasonable rectification.</p>

    <h2>12. Damage and loss</h2>
    <p>Report any damage or loss as soon as possible and before the crew leaves site where practical. We will investigate fairly. Pre-existing damage and wear are not covered.</p>

    <h2>13. Complaints</h2>
    <p>Contact us first on <a href="tel:+{{ config('company.phone') }}">+60 11-1242 8593</a> or <a href="mailto:complaint@cucinow.co">complaint@cucinow.co</a>. We will acknowledge your complaint and reply with next steps. Your statutory rights are not affected.</p>

    <h2>14. Privacy and photos</h2>
    <p>We take site photos only with your permission and handle your data under our <a href="{{ route('legal.privacy') }}">Privacy Policy</a>. Please tell us about confidential areas that must not be photographed.</p>
